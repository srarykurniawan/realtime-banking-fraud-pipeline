-- =====================================================================
-- Snowflake bootstrap: database, schemas, warehouses, RBAC.
-- Run as SECURITYADMIN / SYSADMIN (CI pipeline: schemachange / Terraform snowflake provider).
-- Principle of least privilege: each persona gets exactly what it needs.
-- =====================================================================
USE ROLE SYSADMIN;

CREATE DATABASE IF NOT EXISTS FRAUD_DB DATA_RETENTION_TIME_IN_DAYS = 30;   -- 30 hari time travel (audit)
CREATE SCHEMA IF NOT EXISTS FRAUD_DB.CORE WITH MANAGED ACCESS;
CREATE SCHEMA IF NOT EXISTS FRAUD_DB.OPS  WITH MANAGED ACCESS;
CREATE SCHEMA IF NOT EXISTS FRAUD_DB.MART WITH MANAGED ACCESS;
CREATE SCHEMA IF NOT EXISTS FRAUD_DB.GOVERNANCE WITH MANAGED ACCESS;      -- masking policies & tags

-- Separate compute per workload: streaming loads never compete with BI queries
CREATE WAREHOUSE IF NOT EXISTS FRAUD_STREAM_WH
  WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE
  COMMENT = 'Spark micro-batch MERGE loads';
CREATE WAREHOUSE IF NOT EXISTS FRAUD_TRANSFORM_WH
  WAREHOUSE_SIZE = SMALL AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE
  COMMENT = 'Dynamic tables + Airflow reconciliation';
CREATE WAREHOUSE IF NOT EXISTS FRAUD_BI_WH
  WAREHOUSE_SIZE = SMALL AUTO_SUSPEND = 120 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE
  COMMENT = 'Dashboards & investigation console';

USE ROLE ACCOUNTADMIN;
CREATE RESOURCE MONITOR IF NOT EXISTS FRAUD_MONTHLY_RM WITH CREDIT_QUOTA = 500
  FREQUENCY = MONTHLY START_TIMESTAMP = IMMEDIATELY
  TRIGGERS ON 80 PERCENT DO NOTIFY ON 100 PERCENT DO SUSPEND;
ALTER WAREHOUSE FRAUD_STREAM_WH    SET RESOURCE_MONITOR = FRAUD_MONTHLY_RM;
ALTER WAREHOUSE FRAUD_TRANSFORM_WH SET RESOURCE_MONITOR = FRAUD_MONTHLY_RM;
ALTER WAREHOUSE FRAUD_BI_WH        SET RESOURCE_MONITOR = FRAUD_MONTHLY_RM;

-- ---------------------------------------------------------------- roles
USE ROLE SECURITYADMIN;
CREATE ROLE IF NOT EXISTS FRAUD_PIPELINE_RW   COMMENT = 'Service role: Spark streaming writer';
CREATE ROLE IF NOT EXISTS FRAUD_ORCHESTRATOR  COMMENT = 'Service role: Airflow checks & reconciliation';
CREATE ROLE IF NOT EXISTS FRAUD_ANALYST       COMMENT = 'Fraud investigators: see PII, update dispositions';
CREATE ROLE IF NOT EXISTS FRAUD_BI_READER     COMMENT = 'Dashboard consumers: masked PII, marts only';
CREATE ROLE IF NOT EXISTS FRAUD_ADMIN         COMMENT = 'Platform owners';

GRANT ROLE FRAUD_PIPELINE_RW, FRAUD_ORCHESTRATOR, FRAUD_ANALYST, FRAUD_BI_READER TO ROLE FRAUD_ADMIN;
GRANT ROLE FRAUD_ADMIN TO ROLE SYSADMIN;

GRANT USAGE ON DATABASE FRAUD_DB TO ROLE FRAUD_PIPELINE_RW;
GRANT USAGE ON DATABASE FRAUD_DB TO ROLE FRAUD_ORCHESTRATOR;
GRANT USAGE ON DATABASE FRAUD_DB TO ROLE FRAUD_ANALYST;
GRANT USAGE ON DATABASE FRAUD_DB TO ROLE FRAUD_BI_READER;

-- pipeline writer: CORE + OPS DML only (no DDL on prod tables, temp tables for staging)
GRANT USAGE ON WAREHOUSE FRAUD_STREAM_WH TO ROLE FRAUD_PIPELINE_RW;
GRANT USAGE ON SCHEMA FRAUD_DB.CORE TO ROLE FRAUD_PIPELINE_RW;
GRANT USAGE ON SCHEMA FRAUD_DB.OPS  TO ROLE FRAUD_PIPELINE_RW;
GRANT CREATE TEMPORARY TABLE ON SCHEMA FRAUD_DB.CORE TO ROLE FRAUD_PIPELINE_RW;
GRANT CREATE TEMPORARY TABLE ON SCHEMA FRAUD_DB.OPS  TO ROLE FRAUD_PIPELINE_RW;
GRANT SELECT, INSERT, UPDATE, DELETE ON FUTURE TABLES IN SCHEMA FRAUD_DB.CORE TO ROLE FRAUD_PIPELINE_RW;
GRANT SELECT, INSERT, UPDATE, DELETE ON FUTURE TABLES IN SCHEMA FRAUD_DB.OPS  TO ROLE FRAUD_PIPELINE_RW;

-- orchestrator: read everything, write OPS (check results)
GRANT USAGE ON WAREHOUSE FRAUD_TRANSFORM_WH TO ROLE FRAUD_ORCHESTRATOR;
GRANT USAGE ON ALL SCHEMAS IN DATABASE FRAUD_DB TO ROLE FRAUD_ORCHESTRATOR;
GRANT SELECT ON FUTURE TABLES IN SCHEMA FRAUD_DB.CORE TO ROLE FRAUD_ORCHESTRATOR;
GRANT SELECT, INSERT, UPDATE ON FUTURE TABLES IN SCHEMA FRAUD_DB.OPS TO ROLE FRAUD_ORCHESTRATOR;
GRANT SELECT ON FUTURE DYNAMIC TABLES IN SCHEMA FRAUD_DB.MART TO ROLE FRAUD_ORCHESTRATOR;
GRANT SELECT ON FUTURE VIEWS IN SCHEMA FRAUD_DB.MART TO ROLE FRAUD_ORCHESTRATOR;

-- analysts: read CORE/MART, write dispositions & alert status only
GRANT USAGE ON WAREHOUSE FRAUD_BI_WH TO ROLE FRAUD_ANALYST;
GRANT USAGE ON SCHEMA FRAUD_DB.CORE TO ROLE FRAUD_ANALYST;
GRANT USAGE ON SCHEMA FRAUD_DB.MART TO ROLE FRAUD_ANALYST;
GRANT SELECT ON FUTURE TABLES IN SCHEMA FRAUD_DB.CORE TO ROLE FRAUD_ANALYST;
GRANT SELECT ON FUTURE VIEWS IN SCHEMA FRAUD_DB.MART TO ROLE FRAUD_ANALYST;
GRANT SELECT ON FUTURE DYNAMIC TABLES IN SCHEMA FRAUD_DB.MART TO ROLE FRAUD_ANALYST;

-- BI readers: marts only (PII masked by policy)
GRANT USAGE ON WAREHOUSE FRAUD_BI_WH TO ROLE FRAUD_BI_READER;
GRANT USAGE ON SCHEMA FRAUD_DB.MART TO ROLE FRAUD_BI_READER;
GRANT SELECT ON FUTURE VIEWS IN SCHEMA FRAUD_DB.MART TO ROLE FRAUD_BI_READER;
GRANT SELECT ON FUTURE DYNAMIC TABLES IN SCHEMA FRAUD_DB.MART TO ROLE FRAUD_BI_READER;

-- ---------------------------------------------------------------- service users (key-pair, no password)
CREATE USER IF NOT EXISTS SVC_FRAUD_STREAM
  TYPE = SERVICE DEFAULT_ROLE = FRAUD_PIPELINE_RW DEFAULT_WAREHOUSE = FRAUD_STREAM_WH
  RSA_PUBLIC_KEY = '<paste public key - private key lives in AWS Secrets Manager>'
  COMMENT = 'Spark Structured Streaming job';
CREATE USER IF NOT EXISTS SVC_FRAUD_AIRFLOW
  TYPE = SERVICE DEFAULT_ROLE = FRAUD_ORCHESTRATOR DEFAULT_WAREHOUSE = FRAUD_TRANSFORM_WH
  RSA_PUBLIC_KEY = '<paste public key>'
  COMMENT = 'Airflow (MWAA)';
GRANT ROLE FRAUD_PIPELINE_RW  TO USER SVC_FRAUD_STREAM;
GRANT ROLE FRAUD_ORCHESTRATOR TO USER SVC_FRAUD_AIRFLOW;

-- Only allow service users from the VPC NAT gateway IPs
CREATE NETWORK POLICY IF NOT EXISTS FRAUD_SERVICE_NETWORK_POLICY
  ALLOWED_IP_LIST = ('10.20.0.0/16', '203.0.113.10')   -- ganti dengan IP NAT gateway Anda
  COMMENT = 'Fraud platform service users';
ALTER USER SVC_FRAUD_STREAM  SET NETWORK_POLICY = FRAUD_SERVICE_NETWORK_POLICY;
ALTER USER SVC_FRAUD_AIRFLOW SET NETWORK_POLICY = FRAUD_SERVICE_NETWORK_POLICY;
