-- =====================================================================
-- Snowflake tables (same contract as sql/postgres/01_schema.sql).
-- Timestamps are TIMESTAMP_NTZ in UTC. JSON payloads are stored as VARCHAR
-- (written by MERGE from pandas) and exposed as VARIANT in MART views.
-- =====================================================================
USE ROLE FRAUD_ADMIN;
USE DATABASE FRAUD_DB;

CREATE TABLE IF NOT EXISTS CORE.FCT_TRANSACTIONS (
    TXN_ID               VARCHAR NOT NULL,
    SOURCE_TXN_ID        VARCHAR NOT NULL,
    IDEMPOTENCY_KEY      VARCHAR NOT NULL,
    CONTENT_FINGERPRINT  VARCHAR,
    CHANNEL              VARCHAR NOT NULL,
    CUSTOMER_ID          VARCHAR,
    ACCOUNT_ID           VARCHAR NOT NULL,
    TXN_TYPE             VARCHAR NOT NULL,
    STATUS               VARCHAR NOT NULL,
    AMOUNT               NUMBER(20, 2) NOT NULL,
    CURRENCY             VARCHAR(3) NOT NULL,
    AMOUNT_IDR           NUMBER(20, 2) NOT NULL,
    EVENT_TS             TIMESTAMP_NTZ NOT NULL,
    DEVICE_ID            VARCHAR,
    IP_ADDRESS           VARCHAR,
    MERCHANT_NAME        VARCHAR,
    MCC                  VARCHAR(4),
    COUNTERPARTY_ACCOUNT VARCHAR,
    COUNTERPARTY_BANK    VARCHAR,
    CITY                 VARCHAR,
    COUNTRY_CODE         VARCHAR(2),
    LATITUDE             FLOAT,
    LONGITUDE            FLOAT,
    SOURCE_TOPIC         VARCHAR,
    SOURCE_PARTITION     NUMBER,
    SOURCE_OFFSET        NUMBER,
    INGEST_TS            TIMESTAMP_NTZ,
    IS_DUPLICATE         BOOLEAN DEFAULT FALSE NOT NULL,
    DUPLICATE_TYPE       VARCHAR,
    DUPLICATE_OF         VARCHAR,
    RISK_SCORE           NUMBER(5, 2),
    RISK_LEVEL           VARCHAR,
    DECISION             VARCHAR,
    REASON_CODES         VARCHAR,
    EXPLANATION          VARCHAR,
    RULE_HITS            VARCHAR,
    FEATURES             VARCHAR,
    RULES_VERSION        VARCHAR,
    RULES_HASH           VARCHAR,
    SCORED_AT            TIMESTAMP_NTZ,
    LOADED_AT            TIMESTAMP_NTZ,
    CONSTRAINT PK_FCT_TRANSACTIONS PRIMARY KEY (TXN_ID)          -- informational; MERGE enforces it
)
CLUSTER BY (TO_DATE(EVENT_TS), CHANNEL)
CHANGE_TRACKING = TRUE                                           -- needed by dynamic tables
COMMENT = 'Silver: canonical, de-duplicated, scored transactions';

CREATE TABLE IF NOT EXISTS CORE.TRANSACTION_RULE_HITS (
    TXN_ID VARCHAR NOT NULL, RULE_CODE VARCHAR NOT NULL, WEIGHT FLOAT, EXPLANATION VARCHAR,
    EVIDENCE VARCHAR, ACCOUNT_ID VARCHAR, CHANNEL VARCHAR, EVENT_TS TIMESTAMP_NTZ,
    RULES_VERSION VARCHAR, SCORED_AT TIMESTAMP_NTZ,
    CONSTRAINT PK_RULE_HITS PRIMARY KEY (TXN_ID, RULE_CODE)
) CLUSTER BY (TO_DATE(EVENT_TS)) CHANGE_TRACKING = TRUE;

CREATE TABLE IF NOT EXISTS CORE.FRAUD_ALERTS (
    ALERT_ID VARCHAR NOT NULL, TXN_ID VARCHAR NOT NULL, ACCOUNT_ID VARCHAR, CUSTOMER_ID VARCHAR,
    CHANNEL VARCHAR, EVENT_TS TIMESTAMP_NTZ, AMOUNT_IDR NUMBER(20, 2), RISK_SCORE NUMBER(5, 2),
    RISK_LEVEL VARCHAR, DECISION VARCHAR, REASON_CODES VARCHAR, EXPLANATION VARCHAR,
    ALERT_STATUS VARCHAR, CREATED_AT TIMESTAMP_NTZ,
    CONSTRAINT PK_FRAUD_ALERTS PRIMARY KEY (ALERT_ID)
) CHANGE_TRACKING = TRUE;

CREATE TABLE IF NOT EXISTS CORE.FRAUD_CASE_FEEDBACK (
    TXN_ID VARCHAR NOT NULL, DISPOSITION VARCHAR NOT NULL, ANALYST VARCHAR, NOTES VARCHAR,
    DECIDED_AT TIMESTAMP_NTZ,
    CONSTRAINT PK_FEEDBACK PRIMARY KEY (TXN_ID)
) CHANGE_TRACKING = TRUE;
GRANT INSERT, UPDATE ON TABLE CORE.FRAUD_CASE_FEEDBACK TO ROLE FRAUD_ANALYST;
GRANT UPDATE ON TABLE CORE.FRAUD_ALERTS TO ROLE FRAUD_ANALYST;

CREATE TABLE IF NOT EXISTS CORE.DUPLICATE_EVENTS (
    PIPELINE VARCHAR NOT NULL, BATCH_ID NUMBER NOT NULL, TXN_ID VARCHAR, DUPLICATE_TYPE VARCHAR,
    DUPLICATE_OF VARCHAR, CHANNEL VARCHAR, ACCOUNT_ID VARCHAR, AMOUNT_IDR NUMBER(20, 2),
    EVENT_TS TIMESTAMP_NTZ, SOURCE_TOPIC VARCHAR, SOURCE_PARTITION NUMBER, SOURCE_OFFSET NUMBER,
    DETECTED_AT TIMESTAMP_NTZ
);

CREATE TABLE IF NOT EXISTS CORE.QUARANTINE_EVENTS (
    PIPELINE VARCHAR NOT NULL, BATCH_ID NUMBER NOT NULL, SOURCE_TOPIC VARCHAR, SOURCE_PARTITION NUMBER,
    SOURCE_OFFSET NUMBER, CHANNEL VARCHAR, TXN_ID VARCHAR, ACCOUNT_ID VARCHAR, DQ_ERRORS VARCHAR,
    RAW_PAYLOAD VARCHAR, INGEST_TS TIMESTAMP_NTZ
) DATA_RETENTION_TIME_IN_DAYS = 7;

CREATE TABLE IF NOT EXISTS OPS.PIPELINE_BATCH_METRICS (
    PIPELINE VARCHAR NOT NULL, BATCH_ID NUMBER NOT NULL, BATCH_TS TIMESTAMP_NTZ NOT NULL,
    INPUT_ROWS NUMBER, VALID_ROWS NUMBER, EXACT_DUPLICATES NUMBER, CROSS_DUPLICATES NUMBER,
    QUARANTINED_ROWS NUMBER, ALERTS NUMBER, HOLD_COUNT NUMBER, MIN_EVENT_TS TIMESTAMP_NTZ,
    MAX_EVENT_TS TIMESTAMP_NTZ, PROCESSING_SECONDS FLOAT,
    CONSTRAINT PK_BATCH_METRICS PRIMARY KEY (PIPELINE, BATCH_ID)
) CHANGE_TRACKING = TRUE;

CREATE TABLE IF NOT EXISTS OPS.PIPELINE_HEARTBEAT (
    PIPELINE VARCHAR NOT NULL, LAST_BATCH_ID NUMBER, LAST_BATCH_TS TIMESTAMP_NTZ,
    LAST_EVENT_TS TIMESTAMP_NTZ, STATUS VARCHAR,
    CONSTRAINT PK_HEARTBEAT PRIMARY KEY (PIPELINE)
);

CREATE TABLE IF NOT EXISTS OPS.DQ_CHECK_RESULTS (
    CHECK_NAME VARCHAR NOT NULL, RUN_TS TIMESTAMP_NTZ NOT NULL, STATUS VARCHAR NOT NULL,
    OBSERVED FLOAT, THRESHOLD FLOAT, DETAILS VARCHAR,
    CONSTRAINT PK_DQ_RESULTS PRIMARY KEY (CHECK_NAME, RUN_TS)
);
