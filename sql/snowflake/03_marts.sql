-- =====================================================================
-- Gold layer. KPI tables are DYNAMIC TABLES with TARGET_LAG = 1 minute:
-- Snowflake refreshes them incrementally, so dashboards are ~1-2 minutes
-- behind the transaction (instead of next-day batch).
-- Duplicates (IS_DUPLICATE) are always excluded from business numbers.
-- =====================================================================
USE ROLE FRAUD_ADMIN;
USE SCHEMA FRAUD_DB.MART;

CREATE OR REPLACE DYNAMIC TABLE DT_FRAUD_KPI_HOURLY
  TARGET_LAG = '1 minute' WAREHOUSE = FRAUD_TRANSFORM_WH REFRESH_MODE = INCREMENTAL
AS
SELECT
    DATE_TRUNC('HOUR', EVENT_TS)                                  AS EVENT_HOUR,
    CHANNEL,
    COUNT(*)                                                      AS TXN_COUNT,
    SUM(AMOUNT_IDR)                                               AS TOTAL_AMOUNT_IDR,
    COUNT_IF(DECISION IN ('REVIEW', 'HOLD'))                      AS FLAGGED_COUNT,
    COUNT_IF(DECISION = 'HOLD')                                   AS HOLD_COUNT,
    SUM(IFF(DECISION IN ('REVIEW', 'HOLD'), AMOUNT_IDR, 0))       AS FLAGGED_AMOUNT_IDR,
    AVG(RISK_SCORE)                                               AS AVG_RISK_SCORE
FROM FRAUD_DB.CORE.FCT_TRANSACTIONS
WHERE NOT IS_DUPLICATE
GROUP BY 1, 2;

CREATE OR REPLACE DYNAMIC TABLE DT_CHANNEL_DAILY_SUMMARY
  TARGET_LAG = '5 minutes' WAREHOUSE = FRAUD_TRANSFORM_WH
AS
SELECT
    TO_DATE(EVENT_TS)                                             AS EVENT_DATE,
    CHANNEL,
    COUNT(*)                                                      AS TXN_COUNT,
    COUNT_IF(STATUS = 'SUCCESS')                                  AS SUCCESS_COUNT,
    COUNT_IF(STATUS = 'DECLINED')                                 AS DECLINED_COUNT,
    SUM(IFF(STATUS = 'SUCCESS', AMOUNT_IDR, 0))                   AS SUCCESS_AMOUNT_IDR,
    COUNT(DISTINCT ACCOUNT_ID)                                    AS ACTIVE_ACCOUNTS,
    COUNT_IF(DECISION IN ('REVIEW', 'HOLD'))                      AS FLAGGED_COUNT
FROM FRAUD_DB.CORE.FCT_TRANSACTIONS
WHERE NOT IS_DUPLICATE
GROUP BY 1, 2;

-- Investigation view: everything an analyst needs to answer "why was this flagged?"
CREATE OR REPLACE SECURE VIEW V_ALERT_INVESTIGATION AS
SELECT
    a.ALERT_ID, a.TXN_ID, a.CREATED_AT, a.EVENT_TS, a.CHANNEL, a.ACCOUNT_ID, a.CUSTOMER_ID, a.AMOUNT_IDR,
    a.RISK_SCORE, a.RISK_LEVEL, a.DECISION, a.REASON_CODES, a.EXPLANATION, a.ALERT_STATUS,
    t.TXN_TYPE, t.STATUS, t.MERCHANT_NAME, t.MCC, t.COUNTERPARTY_ACCOUNT, t.CITY, t.COUNTRY_CODE,
    t.DEVICE_ID, t.RULES_VERSION, t.RULES_HASH,
    TRY_PARSE_JSON(t.RULE_HITS)                                   AS RULE_HITS,
    TRY_PARSE_JSON(t.FEATURES)                                    AS FEATURES,
    COALESCE(f.DISPOSITION, 'PENDING')                            AS DISPOSITION,
    f.ANALYST, f.DECIDED_AT
FROM FRAUD_DB.CORE.FRAUD_ALERTS a
JOIN FRAUD_DB.CORE.FCT_TRANSACTIONS t ON t.TXN_ID = a.TXN_ID
LEFT JOIN FRAUD_DB.CORE.FRAUD_CASE_FEEDBACK f ON f.TXN_ID = a.TXN_ID;

CREATE OR REPLACE SECURE VIEW V_RULE_PERFORMANCE AS
SELECT
    h.RULE_CODE, h.RULES_VERSION,
    COUNT(*)                                                      AS HITS,
    COUNT_IF(f.DISPOSITION = 'CONFIRMED_FRAUD')                   AS CONFIRMED_FRAUD,
    COUNT_IF(f.DISPOSITION = 'FALSE_POSITIVE')                    AS FALSE_POSITIVE,
    COUNT_IF(f.DISPOSITION IS NULL)                               AS PENDING_REVIEW,
    DIV0(COUNT_IF(f.DISPOSITION = 'CONFIRMED_FRAUD'), COUNT_IF(f.DISPOSITION IS NOT NULL)) AS PRECISION_RATIO
FROM FRAUD_DB.CORE.TRANSACTION_RULE_HITS h
LEFT JOIN FRAUD_DB.CORE.FRAUD_CASE_FEEDBACK f ON f.TXN_ID = h.TXN_ID
GROUP BY 1, 2;

CREATE OR REPLACE SECURE VIEW V_DATA_QUALITY_DAILY AS
SELECT
    TO_DATE(BATCH_TS) AS BATCH_DATE,
    SUM(INPUT_ROWS) AS INPUT_ROWS, SUM(VALID_ROWS) AS VALID_ROWS,
    SUM(EXACT_DUPLICATES) AS EXACT_DUPLICATES, SUM(CROSS_DUPLICATES) AS CROSS_DUPLICATES,
    SUM(QUARANTINED_ROWS) AS QUARANTINED_ROWS,
    DIV0(SUM(QUARANTINED_ROWS), SUM(INPUT_ROWS)) AS QUARANTINE_RATIO
FROM FRAUD_DB.OPS.PIPELINE_BATCH_METRICS
GROUP BY 1;

CREATE OR REPLACE SECURE VIEW V_QUARANTINE_BY_ERROR AS
SELECT TO_DATE(INGEST_TS) AS INGEST_DATE, SOURCE_TOPIC, e.VALUE::VARCHAR AS DQ_ERROR, COUNT(*) AS EVENTS
FROM FRAUD_DB.CORE.QUARANTINE_EVENTS, LATERAL FLATTEN(INPUT => TRY_PARSE_JSON(DQ_ERRORS)) e
GROUP BY 1, 2, 3;

CREATE OR REPLACE SECURE VIEW V_PIPELINE_HEALTH AS
SELECT PIPELINE, LAST_BATCH_ID, LAST_BATCH_TS, LAST_EVENT_TS, STATUS,
       DATEDIFF('second', LAST_BATCH_TS, SYSDATE()) AS SECONDS_SINCE_LAST_BATCH
FROM FRAUD_DB.OPS.PIPELINE_HEARTBEAT;
