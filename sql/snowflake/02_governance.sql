-- =====================================================================
-- Data protection: PII tagging + dynamic masking.
-- FRAUD_ANALYST / FRAUD_PIPELINE_RW / FRAUD_ADMIN see clear values,
-- everyone else (BI readers) sees masked values. Applied via tag so new
-- PII columns are protected just by tagging them.
-- =====================================================================
USE ROLE FRAUD_ADMIN;
USE SCHEMA FRAUD_DB.GOVERNANCE;

CREATE TAG IF NOT EXISTS PII_LEVEL ALLOWED_VALUES 'IDENTIFIER', 'NETWORK', 'DEVICE'
  COMMENT = 'Personally identifiable information classification';

CREATE MASKING POLICY IF NOT EXISTS MASK_PII_STRING AS (val VARCHAR) RETURNS VARCHAR ->
  CASE
    WHEN IS_ROLE_IN_SESSION('FRAUD_ANALYST') OR IS_ROLE_IN_SESSION('FRAUD_PIPELINE_RW')
         OR IS_ROLE_IN_SESSION('FRAUD_ADMIN') OR IS_ROLE_IN_SESSION('FRAUD_ORCHESTRATOR') THEN val
    WHEN val IS NULL THEN NULL
    WHEN SYSTEM$GET_TAG_ON_CURRENT_COLUMN('FRAUD_DB.GOVERNANCE.PII_LEVEL') = 'IDENTIFIER'
         THEN REPEAT('*', GREATEST(LENGTH(val) - 4, 0)) || RIGHT(val, 4)      -- ******7890
    ELSE SHA2(val, 256)                                                          -- joinable pseudonym
  END;

ALTER TAG PII_LEVEL SET MASKING POLICY MASK_PII_STRING;

-- tag the PII columns (masking follows automatically)
ALTER TABLE FRAUD_DB.CORE.FCT_TRANSACTIONS MODIFY
  COLUMN ACCOUNT_ID           SET TAG GOVERNANCE.PII_LEVEL = 'IDENTIFIER',
  COLUMN CUSTOMER_ID          SET TAG GOVERNANCE.PII_LEVEL = 'IDENTIFIER',
  COLUMN COUNTERPARTY_ACCOUNT SET TAG GOVERNANCE.PII_LEVEL = 'IDENTIFIER',
  COLUMN IP_ADDRESS           SET TAG GOVERNANCE.PII_LEVEL = 'NETWORK',
  COLUMN DEVICE_ID            SET TAG GOVERNANCE.PII_LEVEL = 'DEVICE';

ALTER TABLE FRAUD_DB.CORE.FRAUD_ALERTS MODIFY
  COLUMN ACCOUNT_ID  SET TAG GOVERNANCE.PII_LEVEL = 'IDENTIFIER',
  COLUMN CUSTOMER_ID SET TAG GOVERNANCE.PII_LEVEL = 'IDENTIFIER';

ALTER TABLE FRAUD_DB.CORE.TRANSACTION_RULE_HITS MODIFY
  COLUMN ACCOUNT_ID SET TAG GOVERNANCE.PII_LEVEL = 'IDENTIFIER';

-- raw payloads may contain any PII -> only admins & pipeline can read quarantine
CREATE ROW ACCESS POLICY IF NOT EXISTS RAP_QUARANTINE AS (pipeline VARCHAR) RETURNS BOOLEAN ->
  IS_ROLE_IN_SESSION('FRAUD_ADMIN') OR IS_ROLE_IN_SESSION('FRAUD_PIPELINE_RW')
  OR IS_ROLE_IN_SESSION('FRAUD_ORCHESTRATOR');
ALTER TABLE FRAUD_DB.CORE.QUARANTINE_EVENTS ADD ROW ACCESS POLICY RAP_QUARANTINE ON (PIPELINE);
